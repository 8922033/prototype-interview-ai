@app.route("/chat", methods=["POST"])
def chat():

    try:

        data = request.get_json()

        personality = data.get(
            "personality",
            "passive"
        )

        questions = data.get(
            "questions",
            []
        )

        history = data.get(
            "history",
            []
        )

        prototype_url = data.get(
            "prototype_url",
            ""
        )

        prototype_images = data.get(
            "prototype_images",
            []
        )

        system_prompt = build_system_prompt(
            personality,
            questions,
            prototype_url
        )

        contents = []

        # ---------------------
        # システムプロンプト
        # ---------------------

        contents.append({
            "role": "user",
            "parts": [
                {
                    "text": system_prompt
                }
            ]
        })

        # ---------------------
        # プロトタイプ画像
        # ---------------------

        for image in prototype_images:

            if (
                image.get("data")
                and image.get("mime_type")
            ):

                contents.append({
                    "role": "user",
                    "parts": [
                        {
                            "inline_data": {
                                "mime_type": image["mime_type"],
                                "data": image["data"]
                            }
                        }
                    ]
                })

        # ---------------------
        # 会話履歴
        # ---------------------

        for item in history:

            role = item.get(
                "role",
                "user"
            )

            # JavaScriptのassistantを
            # Gemini用のmodelへ変換
            if role == "assistant":
                role = "model"

            text = item.get(
                "content",
                ""
            )

            contents.append({
                "role": role,
                "parts": [
                    {
                        "text": text
                    }
                ]
            })

        # ---------------------
        # Gemini呼び出し
        # ---------------------

        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=contents
        )

        answer = getattr(
            response,
            "text",
            None
        )

        if not answer:
            answer = (
                "申し訳ありません。"
                "応答を生成できませんでした。"
            )

        return jsonify({
            "success": True,
            "message": answer
        })

    except Exception as e:

        print(e)

        return jsonify({
            "success": False,
            "message": str(e)
        }), 500
